export type Language = keyof typeof strings;
export type Strings = (typeof strings)[Language];

export function appLocale(
  preferences: readonly { languageCode: string | null; languageTag: string }[],
): { language: Language; locale: string } {
  const preference = preferences.find(
    ({ languageCode }) => languageCode === "en" || languageCode === "de",
  );
  return {
    language: preference?.languageCode === "de" ? "de" : "en",
    locale: preference?.languageTag ?? "en-GB",
  };
}
